#Requires -Version 5.1
$ErrorActionPreference = "Stop"

$projectRoot = Split-Path -Parent $PSScriptRoot
Set-Location $projectRoot

function Read-Secret {
    param([string]$Prompt)
    $secure = Read-Host -Prompt $Prompt -AsSecureString
    if ($null -eq $secure) { return "" }

    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
    try {
        $plain = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
    }
    finally {
        [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
    }

    if ($null -eq $plain) { return "" }
    return $plain.Trim()
}

function Show-Status {
    param([string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return "not set" }
    return "set ($($Value.Length) chars)"
}

Write-Host ""
Write-Host "INDmoney SIP Discovery - local API key setup" -ForegroundColor Cyan
Write-Host "The keys are written to .env in this folder and never printed in full." -ForegroundColor DarkGray
Write-Host "Input is hidden while you paste. Press Enter to skip optional keys." -ForegroundColor DarkGray
Write-Host ""

$gemini = Read-Secret "GEMINI_API_KEY (required): "
if ([string]::IsNullOrWhiteSpace($gemini)) {
    Write-Host ""
    Write-Host "A Gemini key is required for the primary extraction run." -ForegroundColor Red
    Write-Host "Create one at https://aistudio.google.com/apikey and run this again." -ForegroundColor Yellow
    exit 1
}

$groq = Read-Secret "GROQ_API_KEY (optional, Enter to skip): "
$mistral = Read-Secret "MISTRAL_API_KEY (optional, Enter to skip): "
$cohere = Read-Secret "COHERE_API_KEY (optional, Enter to skip): "

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# Local secrets for the INDmoney SIP discovery engine")
$lines.Add("# Generated by setup-key.bat. Never commit this file.")
$lines.Add("GEMINI_API_KEY=$gemini")
if (-not [string]::IsNullOrWhiteSpace($groq)) { $lines.Add("GROQ_API_KEY=$groq") }
if (-not [string]::IsNullOrWhiteSpace($mistral)) { $lines.Add("MISTRAL_API_KEY=$mistral") }
if (-not [string]::IsNullOrWhiteSpace($cohere)) { $lines.Add("COHERE_API_KEY=$cohere") }

$envPath = Join-Path $projectRoot ".env"
[System.IO.File]::WriteAllLines($envPath, $lines, (New-Object System.Text.UTF8Encoding($false)))

# Ensure .env is ignored by git
$gitignorePath = Join-Path $projectRoot ".gitignore"
$gitignore = New-Object System.Collections.Generic.List[string]
if (Test-Path $gitignorePath) {
    Get-Content $gitignorePath | ForEach-Object { $gitignore.Add($_) }
}
if (-not ($gitignore -contains ".env")) { $gitignore.Add(".env") }
[System.IO.File]::WriteAllLines($gitignorePath, $gitignore, (New-Object System.Text.UTF8Encoding($false)))

# Best-effort: restrict the .env file to the current Windows user
try {
    $acl = Get-Acl $envPath
    $acl.SetAccessRuleProtection($true, $false)
    $currentUser = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
    $rule = New-Object System.Security.AccessControl.FileSystemAccessRule($currentUser, "Read,Write", "Allow")
    $acl.SetAccessRule($rule)
    Set-Acl -Path $envPath -AclObject $acl
    $permNote = "restricted to your Windows user"
}
catch {
    $permNote = "could not restrict permissions automatically (file is still gitignored)"
}

Write-Host ""
Write-Host "Saved to $envPath" -ForegroundColor Green
Write-Host "  GEMINI_API_KEY  : $(Show-Status $gemini)"
Write-Host "  GROQ_API_KEY    : $(Show-Status $groq)"
Write-Host "  MISTRAL_API_KEY : $(Show-Status $mistral)"
Write-Host "  COHERE_API_KEY  : $(Show-Status $cohere)"
Write-Host "  File permissions: $permNote"
Write-Host ""
Write-Host "Next: double-click check-keys.bat to verify the keys." -ForegroundColor Cyan
